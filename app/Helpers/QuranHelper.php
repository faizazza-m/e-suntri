    public static function getPage($surah, $ayah) {
        if (!is_numeric($surah)) {
            // Find surah number by name
            $surahNum = null;
            foreach (self::$surahs as $num => $s) {
                if (strcasecmp($s["nama"], $surah) === 0 || strcasecmp($s["englishName"], $surah) === 0) {
                    $surahNum = $num;
                    break;
                }
            }
            if (!$surahNum) return 1;
            $surah = $surahNum;
        }
        $surah = (int)$surah;
        $ayah = (int)$ayah;
        for ($i = 604; $i >= 1; $i--) {
            if (!isset(self::$pages[$i])) continue;
            $p = self::$pages[$i];
            if ($p["surah"] < $surah || ($p["surah"] == $surah && $p["ayah"] <= $ayah)) {
                return $i;
            }
        }
        return 1;
    }
    public static function calculatePages($surah, $ayatDari, $ayatSampai) {
        if (empty($ayatDari)) $ayatDari = 1;
        if (empty($ayatSampai)) $ayatSampai = $ayatDari;
        $startPage = self::getPage($surah, $ayatDari);
        $endPage = self::getPage($surah, $ayatSampai);
        return max(1, $endPage - $startPage + 1);
    }
